#!/usr/bin/env python3
"""Generate the two scene culture files that send every AGOT ruler to a vanilla throne room.

AGOT picks its own throne rooms (Casterly Rock, Pyke, the Red Keep, Winterfell...) in
gfx/court_scene/scene_cultures/agot_default_cultures.txt by the ruler's capital, and
locks the vanilla style rooms in its copy of 00_default_cultures.txt behind the line
`agot_has_throne_room = no`. This script rewrites both from the installed AGOT:
every AGOT room gets `trigger = { always = no }`, and the lock line is dropped from the
vanilla style sets, so the ordinary culture triggers (western, mena, byzantine...) pick
the room. Nothing else in the files changes; re-run after an AGOT update.

    tools/make_scene_cultures.py [--agot DIR]
"""
import argparse, os, re

MOD = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEF_AGOT = os.path.expanduser('~/.local/share/Steam/steamapps/workshop/content/1158310/2962333032')
SUB = 'gfx/court_scene/scene_cultures'

def main():
    ap = argparse.ArgumentParser(); ap.add_argument('--agot', default=DEF_AGOT); a = ap.parse_args()
    out = os.path.join(MOD, SUB); os.makedirs(out, exist_ok=True)
    # 1. AGOT's own rooms: keep the set names (the scene files refer to them), disable every trigger
    src = open(os.path.join(a.agot, SUB, 'agot_default_cultures.txt'), encoding='utf-8-sig').read().replace('\r\n', '\n')
    names = re.findall(r'^([a-z_0-9]+)\s*=\s*\{', src, re.M)
    with open(os.path.join(out, 'agot_default_cultures.txt'), 'w', encoding='utf-8') as f:
        f.write('# AGOT Vanilla Courts: every AGOT throne room disabled; generated by tools/make_scene_cultures.py\n')
        for n in names:
            f.write(f'{n} = {{\n\ttrigger = {{\n\t\talways = no\n\t}}\n}}\n')
    # 2. the vanilla style sets: AGOT's copy without the lock
    src = open(os.path.join(a.agot, SUB, '00_default_cultures.txt'), encoding='utf-8-sig').read().replace('\r\n', '\n')
    n_lock = len(re.findall(r'^\s*agot_has_throne_room = no\s*\n', src, re.M))
    dst = re.sub(r'^\s*agot_has_throne_room = no\s*\n', '', src, flags=re.M)
    with open(os.path.join(out, '00_default_cultures.txt'), 'w', encoding='utf-8') as f:
        f.write('# AGOT Vanilla Courts: AGOT\'s 00_default_cultures.txt without the "agot_has_throne_room = no" lock; generated by tools/make_scene_cultures.py\n' + dst)
    print(f'{len(names)} AGOT rooms disabled: {", ".join(names)}')
    print(f'{n_lock} lock lines removed from 00_default_cultures.txt')

if __name__ == '__main__':
    main()
